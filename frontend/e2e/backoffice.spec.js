import { expect, test } from '@playwright/test';

test('administración operativa y acceso denegado a usuario normal', async ({ page }) => {
  await page.goto('login');
  await page.getByLabel('Usuario').fill('e2e_system_admin');
  await page.getByLabel('Contraseña', { exact: true }).fill('e2e_password_123');
  await page.getByRole('button', { name: 'Iniciar sesión' }).click();
  await page.getByRole('link', { name: 'Administración', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Resumen del sistema' })).toBeVisible();
  await page.getByRole('link', { name: 'Usuarios', exact: true }).click();
  await page.getByLabel('Buscar usuario').fill('e2e_other_doctor');
  await page.getByRole('button', { name: 'Buscar' }).click();
  await page.getByRole('link', { name: 'e2e_other_doctor' }).click();
  await page.getByRole('link', { name: 'Ver pacientes asociados' }).click();
  await page.getByRole('link', { name: /PacienteSintetico/ }).click();
  await expect(page.getByText('Expediente administrativo · Solo lectura')).toBeVisible();
  await page.getByRole('link', { name: 'Consultas', exact: true }).click();
  await expect(page.getByText('Consulta sintética')).toBeVisible();
  await page.getByRole('link', { name: 'Usuarios', exact: true }).click();
  await page.getByLabel('Buscar usuario').fill('e2e_other_doctor');
  await page.getByRole('button', { name: 'Buscar' }).click();
  await page.getByRole('link', { name: 'e2e_other_doctor' }).click();
  await page.getByRole('button', { name: 'Desactivar usuario' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Desactivar', exact: true }).click();
  await expect(page.getByText('Estado actualizado.')).toBeVisible();
  await page.getByRole('link', { name: 'Auditoría', exact: true }).click();
  await expect(page.getByText('USER_DEACTIVATED').first()).toBeVisible();
  await page.getByRole('link', { name: 'Usuarios', exact: true }).click();
  await page.getByLabel('Buscar usuario').fill('e2e_other_doctor');
  await page.getByRole('button', { name: 'Buscar' }).click();
  await page.getByRole('link', { name: 'e2e_other_doctor' }).click();
  await page.getByRole('button', { name: 'Activar usuario' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Activar', exact: true }).click();
  await expect(page.getByText('Estado actualizado.')).toBeVisible();
  await page.getByRole('link', { name: 'IA', exact: true }).click();
  await page.getByRole('link', { name: /Ejecución #/ }).first().click();
  await expect(page.getByText('synthetic', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Sistema', exact: true }).click();
  await expect(page.getByText('Base de datos')).toBeVisible();
  await page.getByRole('link', { name: 'Ir a la aplicación' }).click();
  await page.getByRole('button', { name: /Salir/ }).click();
  await expect(page).toHaveURL(/\/app\/login$/);
  await page.getByLabel('Usuario').fill('e2e_doctor');
  await page.getByLabel('Contraseña', { exact: true }).fill('e2e_password_123');
  await page.getByRole('button', { name: 'Iniciar sesión' }).click();
  await expect(page.getByRole('heading', { name: /Bienvenido/ })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Administración', exact: true })).toHaveCount(0);
  await expect.poll(async () => (await page.context().cookies()).some(cookie => cookie.name === 'smile_refresh')).toBe(true);
  await page.goto('/app/backoffice');
  await expect(page.getByRole('heading', { name: 'Acceso no autorizado' })).toBeVisible();
  const login = await page.request.post('/api/v1/auth/login/', { data: { username: 'e2e_doctor', password: 'e2e_password_123' } });
  expect(login.ok()).toBeTruthy();
  const { access } = await login.json();
  for (const path of ['users/', 'patients/', 'appointments/', 'audit/', 'ai-runs/', 'system/']) {
    const response = await page.request.get(`/api/v1/backoffice/${path}`, { headers: { Authorization: `Bearer ${access}` } });
    expect(response.status(), path).toBe(403);
  }
});
